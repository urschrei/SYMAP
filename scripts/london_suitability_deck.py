"""Write examples/decks/london-suitability.sym from examples/data/london-grid-1km.csv.

Two weighted-index maps of the same 1 km grid, after Steinitz's Delmarva
study (1966). The outline and the Thames are taken from london-zones.sym.

    python3 scripts/london_suitability_deck.py
"""

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRID = ROOT / "examples/data/london-grid-1km.csv"
ZONES = ROOT / "examples/decks/london-zones.sym"
OUT = ROOT / "examples/decks/london-suitability.sym"

# Map origin, as in the other London decks: down from northing 202 km,
# across from easting 502.5 km. One kilometre is one printed line down
# and two printed columns across: 2 lines and 2 columns, at the
# printer's 8 lines and 10 columns per inch.
N0, E0 = 202.0, 502.5
ROWS, COLS = 2.0, 2.0
HEADER = f"{'8.':>40}{'10.':>10}"  # rows and columns per inch

# TfL's PTAL bands by access index: 0, 1a, 1b, 2, 3, 4, 5, 6a, 6b.
PTAL_BOUNDS = [0.0, 2.5, 5.0, 10.0, 15.0, 20.0, 25.0, 40.0]


def ptal_score(ai):
    return sum(ai > b for b in PTAL_BOUNDS) / len(PTAL_BOUNDS)


def clip(v):
    return max(0.0, min(1.0, v))


def factors(r):
    return {
        "t": ptal_score(float(r["ptal_ai"])),
        "d": 1.0 - float(r["flood"]),
        "a": clip((43.0 - float(r["no2"])) / (43.0 - 16.0)),
        "g": clip(float(r["green"]) / 0.25),
    }


DECK_HEADER = """
# London: where to build. Two weighted-index maps of one 1 km grid, after
# Carl Steinitz's Delmarva study (Harvard, 1966), which combined mapped
# factors with weighted indexes to rate each 2-mile cell for vegetable and
# for grain farming. As there, the index is worked out before mapping and
# SYMAP only prints it. Generated by scripts/london_suitability_deck.py
# from examples/data/london-grid-1km.csv (scripts/london_grid_1km.py).
#
# Factors, each scaled 0 to 1 per 1 km cell:
#   TRANSIT  PTAL band of the cell's mean 2023 access index (0 to 6b, as
#            eighths). Transport for London, 'PTAL 2023 Grid 100m x 100m',
#            https://gis-tfl.opendata.arcgis.com/ . Powered by TfL Open
#            Data; OGL v3.
#   DRY      share of the cell outside Environment Agency Flood Zones 2
#            and 3 (Flood Map for Planning, rivers and sea, as of October
#            2026), https://environment.data.gov.uk/ . OGL v3.
#   AIR      (43 - NO2) / 27, clipped, from the London Atmospheric
#            Emissions Inventory 2019 modelled annual mean NO2 (20 m grid,
#            averaged to 1 km), Greater London Authority,
#            https://data.london.gov.uk/ . The Datastore page gives no
#            licence; LAEI is usually published under the OGL.
#   PARK     share of the cell that is public park, playing field, play
#            space or other sports facility, full marks at 25%. OS Open
#            Greenspace, October 2026. Contains OS data (c) Crown copyright
#            and database right 2026; OGL v3.
# Cells: every 1 km British National Grid square at least half inside
#   Greater London (London Datastore statistical GIS boundaries; contains
#   OS data (c) Crown copyright), 1,597 in all, as square conformolines.
# Weights: flats near transit 0.60 / 0.25 / 0.15 / 0; family housing 0.25
#   each. Levels are equal numbers of cells (elective 6 left blank), so
#   each map ranks the cells; the two are not on one scale.
# Measurement: rows and columns (8 lines and 10 columns per inch, the
#   header's 8. and 10.). A cell is 2 lines by 2 columns, so it prints
#   aligned to the characters, as on the Delmarva maps, but 1.25 times as
#   tall as wide: the map is stretched north-south. Outline and Thames are
#   those of london-zones.sym, converted to rows and columns.
"""


WEIGHTS = {
    "flats": {"t": 0.60, "d": 0.25, "a": 0.15, "g": 0.00},
    "family": {"t": 0.25, "d": 0.25, "a": 0.25, "g": 0.25},
}


def index(f, w):
    return 100.0 * sum(w[k] * f[k] for k in w)


def rc(down_km, across_km):
    return f"{down_km * ROWS:20.2f}{across_km * COLS:10.2f}"


def zones_packages():
    """The A-OUTLINE and C-OTOLEGENDS packages of london-zones.sym, in km."""
    pkgs, cur = {}, None
    for line in ZONES.read_text().splitlines():
        if line.startswith(("A-OUTLINE", "C-OTOLEGENDS")):
            cur = line.strip()
            pkgs[cur] = []
        elif cur and line.startswith("99999"):
            cur = None
        elif cur:
            pkgs[cur].append(line)
    return pkgs


def rescale(line):
    """Convert one card's km fields (11-20 down, 21-30 across, 31-50 the
    point-legend displacement in characters) to rows and columns."""
    if len(line) < 30 or not line[10:30].strip():
        return line  # a text card
    try:
        down, across = float(line[10:20]), float(line[20:30])
    except ValueError:
        return line
    return line[:10] + f"{down * ROWS:10.2f}{across * COLS:10.2f}" + line[30:]


def main():
    rows = list(csv.DictReader(GRID.open()))
    rows.sort(key=lambda r: (-int(r["y"]), int(r["x"])))
    pkgs = zones_packages()
    out = []
    w = out.append
    w(DECK_HEADER.strip())
    w("A-OUTLINE" + HEADER[9:])
    w("\n".join(rescale(l) for l in pkgs["A-OUTLINE"]))
    w("99999")
    w("A-CONFORMOLINES" + HEADER[15:])
    for i, r in enumerate(rows, 1):
        d = N0 - (int(r["y"]) + 500) / 1000  # top edge
        a = (int(r["x"]) - 500) / 1000 - E0  # left edge
        corners = [(d, a), (d, a + 1), (d + 1, a + 1), (d + 1, a), (d, a)]
        for j, (dd, aa) in enumerate(corners):
            lead = f"{i:5d}    A" if j == 0 else ""
            w(f"{lead:<10}{dd * ROWS:10.2f}{aa * COLS:10.2f}")
    w("99999")
    w("C-OTOLEGENDS" + HEADER[12:])
    w("\n".join(rescale(l) for l in pkgs["C-OTOLEGENDS"]))
    w("99999")
    height = 46.5 * ROWS / 8
    width = 61.0 * COLS / 10
    for name, title in [
        ("flats", "FLATS NEAR TRANSIT"),
        ("family", "FAMILY HOUSING"),
    ]:
        wt = WEIGHTS[name]
        w("E-VALUES")
        for r in rows:
            w(f"{index(factors(r), wt):20.1f}")
        w("99999")
        w("F-MAP")
        w(f"LONDON - RELATIVE ATTRACTIVENESS FOR NEW {title}")
        terms = " + ".join(
            f"{wt[k]:.2f} {lbl}"
            for k, lbl in [("t", "TRANSIT"), ("d", "DRY"), ("a", "AIR"), ("g", "PARK")]
            if wt[k]
        )
        w(f"INDEX = 100 X ({terms})")
        w("WEIGHTED INDEX OF FOUR SITE FACTORS ON A 1 KM GRID")
        w(f"    1{height:15.2f}{width:10.2f}")
        w(f"    2{0:15.2f}{0:10.2f}{height:10.2f}{width:10.2f}")
        w("    3             5.")
        w("    6")
        w("    8")
        w("    9")
        w("   17")
        w("   25")
        w("   10")
        w("TRANSIT: PTAL 2023 BAND, 0 TO 6B. DRY: SHARE OUTSIDE FLOOD ZONES 2-3.")
        w("AIR: LAEI 2019 MODELLED NO2, 43 (WORST) TO 16. PARK: PUBLIC GREEN")
        w("SPACE, FULL MARKS AT A QUARTER OF THE CELL. ~ IS THE RIVER THAMES.")
        w("9999")
        w("99999")
    w("999999")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} cells", file=sys.stderr)


if __name__ == "__main__":
    main()
