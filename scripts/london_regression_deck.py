"""Write examples/decks/london-attractiveness.sym, a regression map after
Steinitz's Boston study, from examples/data/london-grid-1km.csv and
examples/data/london-msoa-prices.csv.

Log median house price per MSOA is regressed by least squares on site
factors of the 1 km cell holding the MSOA's centroid. The fitted equation
is then applied to every cell of the grid and printed as ten equal-count
levels.

    python3 scripts/london_regression_deck.py
"""

import csv
import math
import sys
from pathlib import Path

import numpy as np

from london_suitability_deck import E0, N0, ROOT, zones_packages

GRID = ROOT / "examples/data/london-grid-1km.csv"
PRICES = ROOT / "examples/data/london-msoa-prices.csv"
OUT = ROOT / "examples/decks/london-attractiveness.sym"

CELL = 1000
# Hyde Park Corner, British National Grid metres.
HPC = (528500, 179900)

VARS = [
    ("X1", "KM FROM HYDE PARK CORNER"),
    ("X2", "KM EAST OF HYDE PARK CORNER"),
    ("X3", "PUBLIC GREEN SPACE, SHARE OF THE 3 X 3 KM AROUND"),
    ("X4", "FLOOD ZONES 2-3, SHARE OF THE 3 X 3 KM AROUND"),
    ("X5", "LN(1 + PTAL 2023 ACCESS INDEX)"),
]


def neighbourhood(grid, key, col):
    """Mean of col over the 3 x 3 block of cells centred on key."""
    kx, ky = key
    vals = [
        float(grid[(kx + dx, ky + dy)][col])
        for dx in (-1, 0, 1)
        for dy in (-1, 0, 1)
        if (kx + dx, ky + dy) in grid
    ]
    return sum(vals) / len(vals)


def factors(grid, key):
    r = grid[key]
    x, y = int(r["x"]), int(r["y"])
    return [
        math.hypot(x - HPC[0], y - HPC[1]) / 1000,
        (x - HPC[0]) / 1000,
        neighbourhood(grid, key, "green"),
        neighbourhood(grid, key, "flood"),
        math.log1p(float(r["ptal_ai"])),
    ]


def fit(grid):
    xs, ys = [], []
    for p in csv.DictReader(PRICES.open()):
        key = (int(p["x"]) // CELL, int(p["y"]) // CELL)
        if key in grid:
            xs.append([1.0] + factors(grid, key))
            ys.append(math.log(float(p["price"])))
    X, y = np.array(xs), np.array(ys)
    b, *_ = np.linalg.lstsq(X, y, rcond=None)
    resid = y - X @ b
    r2 = 1 - resid @ resid / ((y - y.mean()) @ (y - y.mean()))
    s2 = resid @ resid / (len(y) - X.shape[1])
    se = np.sqrt(np.diag(s2 * np.linalg.inv(X.T @ X)))
    return b, se, r2, len(y)


def coef(v, digits):
    """A coefficient as Steinitz printed them: no leading zero."""
    s = f"{abs(v):.{digits}f}"
    if s.startswith("0."):
        s = s[1:]
    return ("-" if v < 0 else "+") + s


# Significant figures for each coefficient's printed form.
DIGITS = [2, 3, 4, 2, 2, 3]


def equation(b):
    lead = f"Y = {b[0]:.{DIGITS[0]}f}"
    terms = [f"{coef(v, d)}{name}" for v, d, (name, _) in zip(b[1:], DIGITS[1:], VARS)]
    return lead + "".join(terms)


DECK_HEADER = """
# London: attractiveness for housing, as a regression map after Carl
# Steinitz's Boston study (Harvard, 1967-68; Steinitz and Rogers, 'A
# Systems Analysis Model of Urbanization and Change', MIT Press),
# where an equation fitted to observed data rated each grid cell's
# attractiveness for medium income housing. As there, the equation is
# worked out before mapping and SYMAP only prints it. Generated by
# scripts/london_regression_deck.py.
#
# Dependent variable: natural log of the median price paid for all
#   dwellings in the year ending March 2023, for the {n} London MSOAs
#   whose 2011 boundaries were unchanged in 2021. ONS, 'HPSSA dataset 2:
#   median house prices by MSOA' (table 1a), release of 20 September 2023,
#   https://www.ons.gov.uk/peoplepopulationandcommunity/housing/datasets/
#   hpssadataset2medianhousepricebymsoaquarterlyrollingyear . Contains HM
#   Land Registry data (c) Crown copyright and database right 2023. Each
#   MSOA takes the factors of the 1 km cell holding its centroid (the
#   BNG_E, BNG_N fields of 'Middle layer Super Output Areas (December 2021)
#   Boundaries EW BSC V3', ONS Open Geography Portal). Source: Office for
#   National Statistics licensed under the Open Government Licence v3.0.
#   examples/data/london-msoa-prices.csv (scripts/london_msoa_prices.py).
# Factors, from examples/data/london-grid-1km.csv (scripts/london_grid_1km.py):
#   X1, X2   straight-line distance and distance east (west negative) from
#            Hyde Park Corner (TQ 285 799) to the cell centre, km.
#   X3       share of the 3 x 3 km block centred on the cell that is public
#            park, playing field, play space or other sports facility. OS
#            Open Greenspace, October 2026. Contains OS data (c) Crown
#            copyright and database right 2026; OGL v3.
#   X4       share of the same block in Environment Agency Flood Zones 2 and
#            3 (Flood Map for Planning, October 2026). OGL v3.
#   X5       ln(1 + mean PTAL 2023 access index of the cell). Transport for
#            London, 'PTAL 2023 Grid 100m x 100m'. Powered by TfL Open
#            Data; OGL v3.
# Fit: ordinary least squares, n = {n}, R squared {r2:.2f}. Coefficients
#   (standard errors): {coefs}.
#   Most of the variation in MSOA median prices is left unexplained: the
#   median mixes flats and houses, and the factors are coarse. The map
#   shows the fitted value, not observed prices. A dearer place scores as
#   more attractive, as in Steinitz's model, where observed choices stood
#   for attractiveness. Transit enters with a negative sign once distance
#   from the centre is allowed for: well-served cells are those with more
#   flats.
# Cells: every 1 km British National Grid square at least half inside
#   Greater London, 1,597 in all, as square conformolines. Levels are equal
#   numbers of cells (elective 6 left blank), so the map ranks the cells in
#   tenths.
# Coordinates are kilometres: down from northing 202 km, across from
#   easting 502.5 km; 0.2 inch per km, as on the other London maps. Outline
#   and Thames are those of london-zones.sym.
"""


def main():
    rows = list(csv.DictReader(GRID.open()))
    rows.sort(key=lambda r: (-int(r["y"]), int(r["x"])))
    grid = {(int(r["x"]) // CELL, int(r["y"]) // CELL): r for r in rows}
    b, se, r2, n = fit(grid)
    coefs = ", ".join(
        f"{name} {v:.4f} ({s:.4f})"
        for name, v, s in zip(["const"] + [v[0] for v in VARS], b, se)
    )
    header = DECK_HEADER.format(n=n, r2=r2, coefs=coefs)
    pkgs = zones_packages()
    out = []
    w = out.append
    w("\n".join("# " + l[2:] if l.startswith("# ") else l for l in header.strip().splitlines()))
    w("A-OUTLINE")
    w("\n".join(pkgs["A-OUTLINE"]))
    w("99999")
    w("A-CONFORMOLINES")
    for i, r in enumerate(rows, 1):
        d = N0 - (int(r["y"]) + 500) / 1000
        a = (int(r["x"]) - 500) / 1000 - E0
        corners = [(d, a), (d, a + 1), (d + 1, a + 1), (d + 1, a), (d, a)]
        for j, (dd, aa) in enumerate(corners):
            lead = f"{i:5d}    A" if j == 0 else ""
            w(f"{lead:<10}{dd:10.2f}{aa:10.2f}")
    w("99999")
    w("C-OTOLEGENDS")
    w("\n".join(pkgs["C-OTOLEGENDS"]))
    w("99999")
    w("E-VALUES")
    for r in rows:
        key = (int(r["x"]) // CELL, int(r["y"]) // CELL)
        yhat = b[0] + sum(c * f for c, f in zip(b[1:], factors(grid, key)))
        w(f"{yhat:20.3f}")
    w("99999")
    w("F-MAP")
    w("LONDON - ATTRACTIVENESS FOR HOUSING")
    w(equation(b))
    w("REGRESSION ON MSOA MEDIAN PRICES, 2023, PRINTED ON A 1 KM GRID")
    w("    1           9.30     12.10")
    w("    2           0.00      0.00     46.50     60.50")
    w("    3            10.")
    w("    6")
    w("    8")
    w("    9")
    w("   17")
    w("   25")
    w("   10")
    w("WHERE  Y = LN(MEDIAN PRICE PAID, ALL DWELLINGS, YEAR TO MARCH 2023)")
    for name, label in VARS:
        w(f"      {name} = {label}")
    w(f"FITTED TO {n} MSOAS, R SQUARED {r2:.2f}.  ~ IS THE RIVER THAMES.")
    w(".   1 = LOWEST ATTRACTIVENESS (TENTHS OF THE CELLS)")
    w("   10 = HIGHEST ATTRACTIVENESS")
    w("9999")
    w("99999")
    w("999999")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} cells, R2 {r2:.3f}", file=sys.stderr)
    print(equation(b), file=sys.stderr)


if __name__ == "__main__":
    main()
